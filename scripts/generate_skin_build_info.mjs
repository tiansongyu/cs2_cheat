#!/usr/bin/env node
// Record the actual offset files used by this build; requires no network access.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
let root = fileURLToPath(new URL('..', import.meta.url));
let check = false;
for (let index = 0; index < args.length; index++) {
  if (args[index] === '--check') check = true;
  else if (args[index] === '--root' && args[index + 1]) root = resolve(args[++index]);
  else throw new Error(`Unknown argument: ${args[index]}`);
}
const read = path => readFileSync(resolve(root, path), 'utf8');
const revision = read('last_commit.txt').trim();
if (!/^[a-f0-9]{40}$/.test(revision)) throw new Error('Invalid offset revision');
const headers = ['client_dll.hpp', 'offsets.hpp', 'buttons.hpp'].map(name =>
  read(`external-cheat-base/generated/${name}`));
if (headers.some(header => !header.includes('namespace cs2_dumper'))) throw new Error('Invalid offset header');
const sha = text => createHash('sha256').update(text).digest('hex');
const catalog = JSON.parse(read('external-cheat-base/src/features/skins/SOURCE.json'));
if (!/^[a-f0-9]{40}$/.test(catalog.revision)) throw new Error('Invalid catalog revision');
const values = {
  offsetRevision: revision,
  offsetDate: headers[0].match(/^\/\/ (\d{4}-\d{2}-\d{2}) /m)?.[1] ?? 'unknown',
  clientSha256: sha(headers[0]),
  offsetsSha256: sha(headers[1]),
  buttonsSha256: sha(headers[2]),
  catalogRevision: catalog.revision,
};
const content = '// Generated by scripts/generate_skin_build_info.mjs; do not edit.\n' +
  '#pragma once\n#include <string_view>\n\nnamespace skins::build_info\n{\n' +
  Object.entries(values).map(([key, value]) => `    inline constexpr std::string_view ${key} = ${JSON.stringify(value)};\n`).join('') + '}\n';
const path = resolve(root, 'external-cheat-base/src/features/skins/skin_build_info.hpp');
let previous = '';
try { previous = readFileSync(path, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
if (check && previous !== content) throw new Error('Skin build metadata is stale; run node scripts/generate_skin_build_info.mjs');
if (!check && previous !== content) writeFileSync(path, content);
console.log(`Skin offsets: ${revision.slice(0, 12)} (${values.offsetDate})`);
