#!/usr/bin/env python3
"""Generate a bounded firearms catalog from pinned Valve item metadata.

Input files may be supplied from an installed game; the default inputs are
retrieved from the exact tracking revision below and checked with SHA-256.
No implementation from another skin changer is included.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REVISION = "1e90c3e15dd89504084a1b32def9045528918937"
BASE = f"https://raw.githubusercontent.com/SteamTracking/GameTracking-CS2/{REVISION}/game/csgo/pak01_dir/"
WEAPONS = {1: "deagle", 2: "elite", 3: "fiveseven", 4: "glock", 7: "ak47", 8: "aug",
           9: "awp", 10: "famas", 11: "g3sg1", 13: "galilar", 14: "m249", 16: "m4a1",
           17: "mac10", 19: "p90", 23: "mp5sd", 24: "ump45", 25: "xm1014", 26: "bizon",
           27: "mag7", 28: "negev", 29: "sawedoff", 30: "tec9", 32: "hkp2000", 33: "mp7",
           34: "mp9", 35: "nova", 36: "p250", 38: "scar20", 39: "sg556", 40: "ssg08",
           60: "m4a1_silencer", 61: "usp_silencer", 63: "cz75a", 64: "revolver"}
TOKEN = re.compile(r'//[^\n]*|"(?:\\.|[^"\\])*"|[{}]|[^\s{}"]+')


def keyvalues(text):
    tokens = [m.group() for m in TOKEN.finditer(text.lstrip("\ufeff")) if not m.group().startswith("//")]
    cursor = 0

    def merge(target, incoming):
        # Valve appends additional sections as collections are released.
        for key, value in incoming.items():
            if isinstance(value, dict) and isinstance(target.get(key), dict):
                merge(target[key], value)
            else:
                target[key] = value

    def atom(token):
        if token.startswith('"'):
            return re.sub(r'\\([\\"nrt])', lambda m: {"n": "\n", "r": "\r", "t": "\t"}.get(m[1], m[1]), token[1:-1])
        return token

    def block(nested=False):
        nonlocal cursor
        result = {}
        while cursor < len(tokens):
            key = tokens[cursor]
            cursor += 1
            if key == "}":
                if not nested:
                    raise ValueError("Unexpected closing brace")
                return result
            if cursor == len(tokens):
                raise ValueError("Missing value")
            value = tokens[cursor]
            cursor += 1
            merge(result, {atom(key): block(True) if value == "{" else atom(value)})
            # Conditional key/value entries are immaterial to these sections.
            if cursor < len(tokens) and tokens[cursor].startswith("[$"):
                cursor += 1
        if nested:
            raise ValueError("Unclosed block")
        return result

    return block()


def generate(items, language):
    game = keyvalues(items)["items_game"]
    tokens = {k.lower(): v for k, v in keyvalues(language)["lang"]["Tokens"].items()}
    kits = {value["name"]: (int(key), value) for key, value in game["paint_kits"].items() if key.isdigit()}
    pairs = set()
    weapon_ids = {"weapon_" + name: key for key, name in WEAPONS.items()}

    def visit(node):
        for key, value in node.items():
            match = re.fullmatch(r"\[([^\]]+)\](weapon_.+)", key)
            if match and match[2] in weapon_ids and match[1] in kits:
                pairs.add((weapon_ids[match[2]], match[1]))
            if isinstance(value, dict):
                visit(value)

    visit(game["item_sets"])
    rows = []
    for weapon, name in pairs:
        kit_id, kit = kits[name]
        label = tokens.get(kit.get("description_tag", "").lstrip("#").lower(), name)
        minimum = float(kit.get("wear_remap_min", "0"))
        maximum = float(kit.get("wear_remap_max", "1"))
        if not 0 <= minimum <= maximum <= 1 or not 0 < kit_id < 10000:
            raise ValueError(f"Invalid paint kit: {kit_id}")
        rows.append((weapon, label, kit_id, minimum, maximum, kit.get("use_legacy_model") == "1"))
    rows.sort(key=lambda row: (row[0], row[1].casefold(), row[2]))
    if len(rows) < 900 or len({row[0] for row in rows}) != len(WEAPONS):
        raise ValueError("Incomplete firearm catalog")
    lines = ["// Generated by scripts/generate_skin_catalog.py; do not edit.",
             f"// Valve item metadata tracked at {REVISION}.", "#pragma once", "", "namespace skins", "{",
             f"    inline constexpr std::array<PaintKit, {len(rows)}> paintKits{{{{"]
    for weapon, label, kit_id, minimum, maximum, legacy in rows:
        lines.append(f"        {{{weapon}, {kit_id}, {json.dumps(label, ensure_ascii=True)}, {minimum:.6f}f, {maximum:.6f}f, {'true' if legacy else 'false'}}},")
    lines += ["    }};", "}", ""]
    return "\n".join(lines), len(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--items", type=Path)
    parser.add_argument("--language", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source_path = ROOT / "external-cheat-base/src/features/skins/SOURCE.json"
    sources = json.loads(source_path.read_text())
    bodies = []
    for local, name in [(args.items, "scripts/items/items_game.txt"), (args.language, "resource/csgo_english.txt")]:
        body = local.read_bytes() if local else urllib.request.urlopen(BASE + name, timeout=30).read()
        if hashlib.sha256(body).hexdigest() != sources["sha256"][name]:
            raise ValueError(f"Source hash mismatch: {name}")
        bodies.append(body.decode("utf-8-sig"))
    result, count = generate(*bodies)
    destination = ROOT / "external-cheat-base/src/features/skins/skin_catalog_data.hpp"
    if args.check:
        if destination.read_text() != result:
            raise SystemExit("Skin catalog is out of date")
    else:
        destination.write_text(result)
    print(f"Skin catalog: {len(WEAPONS)} firearms, {count} weapon/paint-kit pairs")


if __name__ == "__main__":
    main()
